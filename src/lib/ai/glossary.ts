function lemmaCandidates(word: string): string[] {
  const candidates: string[] = []

  if (word.endsWith('ies')) candidates.push(`${word.slice(0, -3)}y`)
  if (word.endsWith('ied')) candidates.push(`${word.slice(0, -3)}y`)
  if (word.endsWith('est')) candidates.push(word.slice(0, -3))
  if (word.endsWith('er')) candidates.push(word.slice(0, -2))
  if (word.endsWith('ly')) {
    candidates.push(word.slice(0, -2))
    if (word.endsWith('ily')) candidates.push(`${word.slice(0, -3)}y`)
  }
  if (word.endsWith('ing')) {
    candidates.push(word.slice(0, -3))
    candidates.push(`${word.slice(0, -3)}e`)
    if (word.length > 5 && word[word.length - 4] === word[word.length - 5]) {
      candidates.push(word.slice(0, -4))
    }
  }
  if (word.endsWith('ed')) {
    candidates.push(word.slice(0, -2))
    candidates.push(word.slice(0, -1))
    if (word.length > 4 && word[word.length - 3] === word[word.length - 4]) {
      candidates.push(word.slice(0, -3))
    }
  }
  if (word.endsWith('es')) candidates.push(word.slice(0, -2))
  if (word.endsWith('s') && !word.endsWith('ss')) candidates.push(word.slice(0, -1))

  return candidates.filter((candidate) => candidate.length >= 3)
}

export function lookupGloss(raw: string): { lemma: string; zh: string } | undefined {
  const word = raw
    .toLowerCase()
    .replace(/’/g, "'")
    .replace(/^[^a-z]+|[^a-z]+$/g, '')

  if (!word) return undefined
  if (GLOSSARY[word]) return { lemma: word, zh: GLOSSARY[word] }

  for (const candidate of lemmaCandidates(word)) {
    if (GLOSSARY[candidate]) {
      return { lemma: candidate, zh: GLOSSARY[candidate] }
    }
  }

  return undefined
}
